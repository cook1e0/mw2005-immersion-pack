# Generates src/d3d9device_gen.h: a forwarding IDirect3DDevice9 wrapper base class
# from the Windows SDK's d3d9.h. Methods listed in OVERRIDDEN are left pure-virtual-free
# (declared only) so d3d9proxy.cpp can implement them.
import re, sys
src, out = sys.argv[1], sys.argv[2]
text = open(src).read()
body = re.search(r'DECLARE_INTERFACE_\(IDirect3DDevice9, IUnknown\)\s*\{(.*?)\n\};', text, re.S).group(1)
body = re.sub(r'/\*.*?\*/', '', body, flags=re.S)
methods = re.findall(r'STDMETHOD(?:_\((\w+)\s*,\s*(\w+)\)|\((\w+)\))\s*\(THIS_?\s*(.*?)\)\s*PURE;', body, re.S)
OVERRIDDEN = {'SetRenderTarget', 'QueryInterface', 'AddRef', 'Release', 'Reset', 'Present', 'CreateTexture', 'CreateVolumeTexture',
              'CreateCubeTexture', 'CreateVertexBuffer', 'CreateIndexBuffer'}
lines = ['// Generated by tools/gen_device_wrapper.py from d3d9.h - do not edit.',
         '#pragma once', '#include <d3d9.h>', '',
         'class DeviceWrapBase : public IDirect3DDevice9 {', 'public:',
         '    IDirect3DDevice9Ex* real;', '    explicit DeviceWrapBase(IDirect3DDevice9Ex* r) : real(r) {}']
for ret, name1, name2, args in methods:
    name = name1 or name2
    ret = ret or 'HRESULT'
    args = ' '.join(args.split())
    params = [a.strip() for a in args.split(',') if a.strip()]
    names, decls = [], []
    for i, p in enumerate(params):
        p = re.sub(r'\[.*?\]', '', p).strip()
        toks = p.replace('*', ' * ').split()
        named = len([t for t in toks if t not in ('CONST', 'const', '*')]) >= 2 and re.match(r'^\w+$', toks[-1])
        typ = ' '.join(toks[:-1]) if named else ' '.join(toks)
        names.append('a%d' % i)
        decls.append('%s a%d' % (typ, i))
    args = ', '.join(decls)
    sig = '    %s STDMETHODCALLTYPE %s(%s)' % (ret, name, args)
    if name in OVERRIDDEN:
        lines.append(sig + ' override = 0;')
    else:
        call = 'real->%s(%s)' % (name, ', '.join(names))
        lines.append(sig + ' override { %s%s; }' % ('' if ret == 'void' else 'return ', call))
lines.append('};')
open(out, 'w').write('\n'.join(lines) + '\n')
print(len(methods), 'methods')
